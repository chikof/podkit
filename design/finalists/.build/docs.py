def theme_snippet(slug):
    T = C.load(f"{ROOT}/{slug}/tokens.css"); name = NAMES[slug]; out = [f"/* podkit theme.css block for {name}: paste into the FIRST :root block (color tokens only, one per line). Generated from tokens.css; oklch, light-dark(<light>, <dark>). */", ":root {"]
