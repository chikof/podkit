def hex_to_rgb(h): h = h.lstrip("#"); return tuple(int(h[i:i+2], 16) for i in (0, 2, 4))
def srgb_lin(c): c /= 255; return c / 12.92 if c <= .04045 else ((c + .055) / 1.055) ** 2.4
def oklch(rgb, a=None):
    r, g, b = (srgb_lin(x) for x in rgb)
    l = .4122214708 * r + .5363325363 * g + .0514459929 * b; m = .2119034982 * r + .6806995451 * g + .1073969566 * b; s = .0883024619 * r + .2817188376 * g + .6299787005 * b
    l, m, s = l ** (1 / 3), m ** (1 / 3), s ** (1 / 3)
    L = .2104542553 * l + .793617785 * m - .0040720468 * s; A = 1.9779984951 * l - 2.428592205 * m + .4505937099 * s; B = .0259040371 * l + .7827717662 * m - .808675766 * s
    Cc = math.hypot(A, B); H = math.degrees(math.atan2(B, A)) % 360
    if Cc < .004: H = 0
    return f"oklch({L:.3f} {Cc:.3f} {H:.1f}" + (f" / {a:g}%)" if a is not None else ")")
def val_to_oklch(v):
    v = v.strip()
    m = re.fullmatch(r"#([0-9a-fA-F]{6})", v)
    if m: return oklch(hex_to_rgb(v))
    m = re.fullmatch(r"rgb\(\s*(\d+)\s+(\d+)\s+(\d+)\s*/\s*([\d.]+)\)", v)
    if m: return oklch(tuple(int(m.group(i)) for i in (1, 2, 3)), round(float(m.group(4)) * 100))
    return None

