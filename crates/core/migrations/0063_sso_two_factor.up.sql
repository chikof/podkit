-- SSO (OIDC and GitHub OAuth), two-factor sign-in (TOTP, recovery codes, passkeys),
-- the team "require 2FA" policy and a session list (roadmap B7).

-- An account made by "Sign in with ..." has no password the person knows: it holds a random
-- one nobody sees. `has_password` says whether a password check means anything for it.
ALTER TABLE users ADD COLUMN has_password BOOLEAN NOT NULL DEFAULT TRUE;

-- Sessions get an id (so one can be revoked without showing its hash) and where they began.
ALTER TABLE sessions ADD COLUMN id BIGINT GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE sessions ADD CONSTRAINT sessions_id_key UNIQUE (id);
ALTER TABLE sessions ADD COLUMN method TEXT NOT NULL DEFAULT 'password'
	CHECK (method IN ('password', 'sso', 'passkey'));
ALTER TABLE sessions ADD COLUMN ip TEXT;
ALTER TABLE sessions ADD COLUMN user_agent TEXT;

-- An identity provider: the whole instance's (`team_id` NULL, set by the instance
-- administrator) or one team's.
CREATE TABLE auth_providers (
	id BIGINT PRIMARY KEY NOT NULL,
	team_id BIGINT REFERENCES teams(id) ON DELETE CASCADE,
	kind TEXT NOT NULL CHECK (kind IN ('oidc', 'github')),
	-- The path segment of its sign-in address; unique per owner.
	slug VARCHAR(40) NOT NULL,
	name VARCHAR(60) NOT NULL,
	-- OIDC: the issuer URL discovery starts from. GitHub: a GitHub Enterprise base URL, or
	-- NULL for github.com.
	issuer TEXT,
	client_id TEXT NOT NULL,
	-- Encrypted with the instance secret box; never shown again.
	client_secret BYTEA NOT NULL,
	scopes TEXT NOT NULL DEFAULT 'openid email profile',
	-- Make an account on first sign-in (when the registration policy allows one).
	jit BOOLEAN NOT NULL DEFAULT TRUE,
	-- Accept an email the provider does not vouch for (Microsoft sends no `email_verified`).
	allow_unverified_email BOOLEAN NOT NULL DEFAULT FALSE,
	-- Team providers only: which claim lists the person's groups, and what role each group
	-- gives: `[{"group": "ops", "role_id": 1}]`.
	group_claim TEXT,
	group_roles JSONB NOT NULL DEFAULT '[]'::jsonb,
	enabled BOOLEAN NOT NULL DEFAULT TRUE,
	created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE UNIQUE INDEX auth_providers_slug_key ON auth_providers (COALESCE(team_id, 0), slug);

-- Which account a provider's subject signs in to.
CREATE TABLE user_identities (
	id BIGINT PRIMARY KEY NOT NULL,
	provider_id BIGINT NOT NULL REFERENCES auth_providers(id) ON DELETE CASCADE,
	user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
	subject TEXT NOT NULL,
	email TEXT,
	created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
	UNIQUE (provider_id, subject)
);
CREATE INDEX idx_user_identities_user ON user_identities (user_id);

-- Short-lived state between two requests of a sign-in: the OIDC round trip, the wait for a
-- second factor, the wait for a password to link an account, a WebAuthn ceremony. The
-- browser holds a random token; only its digest is stored.
CREATE TABLE auth_flows (
	token_hash BYTEA PRIMARY KEY NOT NULL,
	kind TEXT NOT NULL CHECK (kind IN ('oidc', 'link', 'second_factor', 'passkey_login', 'passkey_enroll')),
	user_id BIGINT REFERENCES users(id) ON DELETE CASCADE,
	provider_id BIGINT REFERENCES auth_providers(id) ON DELETE CASCADE,
	data JSONB NOT NULL DEFAULT '{}'::jsonb,
	attempts INTEGER NOT NULL DEFAULT 0,
	created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
	expires_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX idx_auth_flows_expires ON auth_flows (expires_at);

-- An authenticator app. Unconfirmed until the person proves it with a code.
CREATE TABLE totp_credentials (
	user_id BIGINT PRIMARY KEY NOT NULL REFERENCES users(id) ON DELETE CASCADE,
	-- The base32 secret, encrypted with the instance secret box.
	secret BYTEA NOT NULL,
	confirmed_at TIMESTAMPTZ,
	-- The newest time step accepted, so one code cannot be used twice.
	last_step BIGINT NOT NULL DEFAULT 0,
	created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE recovery_codes (
	id BIGINT PRIMARY KEY NOT NULL,
	user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
	-- SHA-256 of the code without dashes; the code itself is shown once.
	code_hash BYTEA NOT NULL,
	used_at TIMESTAMPTZ,
	created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX idx_recovery_codes_user ON recovery_codes (user_id);

CREATE TABLE passkeys (
	id BIGINT PRIMARY KEY NOT NULL,
	user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
	name VARCHAR(60) NOT NULL,
	-- WebAuthn credential id, for finding the row after a sign-in.
	credential_id BYTEA NOT NULL UNIQUE,
	-- The `webauthn_rs::Passkey`: public key and signature counter.
	credential JSONB NOT NULL,
	created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
	last_used_at TIMESTAMPTZ
);
CREATE INDEX idx_passkeys_user ON passkeys (user_id);

-- "Require 2FA for members": members without a second factor are shut out of the team
-- from `require_2fa_deadline` (the day it was switched on plus the grace period).
ALTER TABLE teams ADD COLUMN require_2fa BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE teams ADD COLUMN require_2fa_deadline TIMESTAMPTZ;
ALTER TABLE teams ADD COLUMN require_2fa_grace_days INTEGER NOT NULL DEFAULT 7
	CHECK (require_2fa_grace_days BETWEEN 0 AND 90);
