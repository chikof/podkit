/// Refuses a state-changing request whose `Origin` is not this site. The
/// expected site is `X-Forwarded-Host` when a proxy sets it, else `Host`, so
/// it works over plain HTTP. A request with no `Origin` (curl, not a browser
/// form) passes unless the browser says it came from another site.
async fn origin_guard(req: Request, next: Next) -> Response {
	let safe = matches!(*req.method(), Method::GET | Method::HEAD | Method::OPTIONS);
	if safe || same_origin(req.headers()) {
		next.run(req).await
	} else {
		(StatusCode::FORBIDDEN, "cross-origin request refused").into_response()
	}
}

/// Where sign-in may send the browser afterwards: a path on this site, never
/// another origin (`//host`, `/\host`, `https://host`).
pub(crate) fn safe_next(next: &str) -> &str {
	let ok = next.starts_with('/')
		&& !next.starts_with("//")
		&& !next.contains('\\')
		&& !next.chars().any(char::is_control);
	if ok { next } else { "/" }
}

fn immutable(content_type: &'static str, body: &'static str) -> impl IntoResponse {
	(
		[
			(header::CONTENT_TYPE, content_type),
			(header::CACHE_CONTROL, "public, max-age=31536000, immutable"),
		],
		body,
	)
}

async fn datastar_js() -> impl IntoResponse {
	immutable("text/javascript; charset=utf-8", DATASTAR_JS)
}

async fn app_css() -> impl IntoResponse {
	immutable("text/css; charset=utf-8", APP_CSS)
}

/// A signed-in user goes to their first team; with none they create one.
async fn index(State(s): State<AppState>, user: UiUser) -> Response {
	match podkit_core::teams::list_for_user(&s.db, user.id).await {
		Ok(teams) => match teams.first() {
			Some(team) => Redirect::to(&format!("/teams/{}/projects", team.id)).into_response(),
			None => layout::bare_page(
				Some(&user.name),
				"Create a team",
				&pages::accounts::create_form(
					"You aren't in a team yet. Create one to get started.",
				),
			)
			.into_response(),
		},
		Err(e) => error::bare(Some(&user), &e.into()),
	}
}

#[derive(Deserialize)]
struct LoginQuery {
	next: Option<String>,
	/// A team's slug: its identity providers are offered next to the instance's.
	team: Option<String>,
}

/// "Sign in with ...": one button per enabled provider, then a passkey button (shown by
/// `passkey.js` when the browser can use one).
fn provider_buttons(buttons: &[podkit_core::sso::providers::Button], next: &str) -> Markup {
	let query: String = url::form_urlencoded::byte_serialize(next.as_bytes()).collect();
	html! {
		div class="ui-auth-alt-actions" {
			@for b in buttons {
				a class="ui-button ui-button-outline ui-button-lg ui-button-block" href={ "/sso/" (b.id) "/start?next=" (query) } {
					@if b.kind == podkit_core::sso::Kind::Github { (components::logo("github", components::LogoSize::Sm)) } @else { (icon("key-round")) }
					span { "Sign in with " (b.name) }
				}
			}
			button type="button" class="ui-button ui-button-outline ui-button-lg ui-button-block" data-passkey="login" hidden {
				(icon("key-round"))
				span { "Sign in with a passkey" }
			}
			p class="ui-hint" data-passkey-status role="status" {}
			p class="ui-hint" data-passkey-note hidden { "Passkeys need a secure connection (HTTPS)." }
		}
	}
}

async fn login_page(State(s): State<AppState>, Query(query): Query<LoginQuery>) -> Response {
	// Where to go next can name something private: keep such a page out of caches and
	// referrers.
	let private = query.next.is_some();
	// A failed lookup hides the link: better no link than one that 403s.
	let can_register = auth::service::registration_allowed(&s.db, s.config.registration)
		.await
		.unwrap_or(false);
	let next = safe_next(query.next.as_deref().unwrap_or("/"));
	let buttons = podkit_core::sso::providers::buttons(&s.db, query.team.as_deref())
		.await
		.unwrap_or_default();
	let signals = format!(
		"{{email: '', password: '', next: {}, _error: ''}}",
		sse::js_string(next)
	);
	let card = html! {
		div class="ui-auth-head" {
			h1 id="auth-t" { "Sign in to podkit" }
			p class="ui-lede" { "Use the email and password of your podkit account." }
		}
		form class="ui-auth-form" "data-on:submit"="evt.preventDefault(); @post('/login')" {
			div class="ui-field-group" {
				label class=(LABEL) for="si-email" { "Email" }
				input id="si-email" class=(INPUT) type="email" autocomplete="username" required autofocus placeholder="you@example.com" "data-bind:email";
			}
			div class="ui-field-group" {
				label class=(LABEL) for="si-pw" { "Password" }
				div class="ui-pw" {
					input id="si-pw" class=(INPUT) type="password" autocomplete="current-password" required "data-bind:password";
					(reveal_button())
				}
			}
			(form_banner())
			p class="ui-auth-foot" "data-show"="!window.isSecureContext" style="display: none" {
				"This connection isn't encrypted, so your password and session travel in plain text. Use HTTPS when podkit is reachable from other machines."
			}
			button type="submit" class={ (BUTTON) " ui-button-lg ui-button-block" } "data-indicator:_busy" "data-attr:disabled"="$_busy" "data-attr:aria-busy"="$_busy" {
				span { "Sign in" }
				(icon("arrow-right"))
			}
		}
		div class="ui-auth-or" role="separator" { span { "or" } }
		(provider_buttons(&buttons, next))
		(assets::passkey_script())
		@if can_register {
			p class="ui-auth-foot" { "No account yet? " a href="/register" { "Create one" } }
		} @else {
			p class="ui-auth-foot" { "Ask an owner to add you if you do not have an account yet." }
		}
	};
	let page = layout::auth_page("Sign in", Some(&signals), &card, Some(&layout::auth_meta()));
	if private {
		(
			[
				(header::CACHE_CONTROL, "no-store"),
				(header::REFERRER_POLICY, "no-referrer"),
			],
			page,
		)
			.into_response()
	} else {
		page.into_response()
	}
}

#[derive(Deserialize)]
struct LoginSignals {
	#[serde(flatten)]
	credentials: Credentials,
	#[serde(default)]
	next: String,
}

async fn login(
	State(s): State<AppState>,
	cookies: Cookies,
	headers: HeaderMap,
	ReadSignals(signals): ReadSignals<LoginSignals>,
) -> Response {
	let next = safe_next(&signals.next).to_owned();
	let Credentials {
		email, password, ..
	} = signals.credentials;
	// Password first. An account with two-step verification is parked until it gives the
	// second factor; any other gets its session now.
	let outcome = async {
		let user = auth::verify_password(&s.db, &email, password).await?;
		if podkit_core::two_factor::service::enrolled(&s.db, user).await? {
			podkit_core::two_factor::challenge::begin(&s, &cookies, &headers, user, &next).await?;
			return Ok("/login/two-step".to_owned());
		}
		auth::open_session(
			&s,
			&cookies,
			&headers,
			user,
			auth::session::Method::Password,
		)
		.await?;
		Ok::<_, ServerError>(next.clone())
	}
	.await;
	let message = match outcome {
		Ok(to) => return sse::redirect(&to).into_response(),
		Err(ServerError::InvalidCredentials) => "Wrong email or password.".to_owned(),
		Err(e @ ServerError::TooManyAttempts { .. }) => e.to_string(),
		Err(e) => {
			tracing::error!(error = %e, "ui login failed");
			"Sign-in failed. Try again.".to_owned()
		}
	};
	sse::signals(&serde_json::json!({ "_error": message, "password": "" })).into_response()
}

async fn logout(
	State(s): State<AppState>,
	cookies: Cookies,
	token: Result<SessionToken, ServerError>,
) -> Response {
	if let Ok(SessionToken(token)) = token
		&& let Err(e) = auth::log_out(&s, &cookies, &token).await
	{
		return e.into_response();
	}
	Redirect::to("/login").into_response()
}
