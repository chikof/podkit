/// Versioned so browsers can cache it forever; bump with the vendored file.
const DATASTAR_PATH: &str = "/static/datastar-1.0.5.js";
const DATASTAR_JS: &str = include_str!("../static/datastar-1.0.5.js");

/// Generated by `build.rs` from the utility classes used in `src/ui`.
const APP_CSS: &str = include_str!(concat!(env!("OUT_DIR"), "/app.css"));

/// `/static/app.css?v=<content hash>`: a new hash on every stylesheet change
/// lets browsers cache each version forever.
static APP_CSS_HREF: LazyLock<String> = LazyLock::new(|| {
	let hash = Sha256::digest(APP_CSS.as_bytes());
	let short = URL_SAFE_NO_PAD.encode(&hash[..6]);
	format!("/static/app.css?v={short}")
});

/// The answer for a path no route matches: the 404 page for a browser, an empty 404 for
/// the API and for anything that is not a page request.
pub async fn not_found(method: Method, uri: axum::http::Uri) -> Response {
	let is_page = (method == Method::GET || method == Method::HEAD)
		&& !uri.path().starts_with("/api/")
		&& !uri.path().starts_with("/webhooks/");
	if is_page {
		error::bare(None, &ServerError::NotFound)
	} else {
		StatusCode::NOT_FOUND.into_response()
	}
}

/// The whole application: the router of `podkit-core` (the JSON API, the MCP endpoint, the
/// webhooks) with the web UI at the root and the 404 page as the fallback.
pub async fn routes(state: AppState) -> AppResult<Router> {
	podkit_core::routes::routes_with(state, |public| public.merge(router()).fallback(not_found))
		.await
}

